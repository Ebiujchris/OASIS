import { defineArrayMember, defineField, defineType } from "sanity";

const textItems = (name: string, title: string, group: string) =>
  defineField({
    name,
    title,
    type: "array",
    of: [defineArrayMember({ type: "string" })],
    group,
  });

const imageField = (name: string, title: string, group: string) =>
  defineField({
    name,
    title,
    type: "image",
    options: { hotspot: true },
    group,
    fields: [
      defineField({
        name: "alt",
        title: "Alternative text",
        type: "string",
      }),
    ],
  });

const contentItems = (
  name: string,
  title: string,
  group: string,
  fields: ReturnType<typeof defineField>[],
) =>
  defineField({
    name,
    title,
    type: "array",
    group,
    of: [
      defineArrayMember({
        type: "object",
        fields,
      }),
    ],
  });

